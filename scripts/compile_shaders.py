"""Compiles shaders/*.vert|*.frag to SPIR-V and embeds them in src/render/shaders_spirv.inc.

Run after changing a shader:  python3 scripts/compile_shaders.py
Needs glslangValidator (Vulkan SDK or the glslang-tools package). The generated file is
committed so normal builds need no shader compiler. D3D12/Metal variants will be produced
from the same SPIR-V with SDL_shadercross.
"""
import os
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src_dir = os.path.join(root, "shaders")
out_path = os.path.join(root, "src", "render", "shaders_spirv.inc")

lines = ["// Generated by scripts/compile_shaders.py. Do not edit.", ""]
entries = []
with tempfile.TemporaryDirectory() as tmp:
    for name in sorted(os.listdir(src_dir)):
        if not name.endswith((".vert", ".frag")):
            continue
        spv = os.path.join(tmp, name + ".spv")
        subprocess.run(["glslangValidator", "-V", "--quiet", os.path.join(src_dir, name), "-o", spv], check=True)
        data = open(spv, "rb").read()
        ident = "k_" + name.replace(".", "_")
        lines.append(f"static const unsigned char {ident}[] = {{")
        for i in range(0, len(data), 20):
            lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
        lines.append("};")
        entries.append((name, ident))
lines.append("")
lines.append("static const EmbeddedShader k_shaders[] = {")
for name, ident in entries:
    lines.append(f'    {{"{name}", {ident}, sizeof({ident})}},')
lines.append("};")
open(out_path, "w").write("\n".join(lines) + "\n")
print(f"wrote {len(entries)} shaders to {os.path.relpath(out_path, root)}")
